import {test,expect} from '@playwright/test'
import {setFilters,draw} from './helpers'

test('mobile dashboard discovers packs across dimensions and opens an inspectable selection',async({page})=>{
  await page.setViewportSize({width:320,height:800});await page.goto('/')
  await expect(page.getByRole('button',{name:'Browse packs',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByRole('button',{name:'Open pack HSK 1',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Practice 一',exact:true})).toHaveCount(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'/tmp/hanzi-dashboard-mobile.png',fullPage:false})
  await page.getByRole('button',{name:'Study sets',exact:true}).click()
  await expect(page.getByRole('button',{name:'Open pack Set 12 · More of the world'})).toBeVisible()
  await page.getByPlaceholder('Find a pack: food, HSK 1, numbers…').fill('food')
  await page.getByRole('button',{name:'Open pack Food & drink',exact:true}).click()
  await expect(page.getByRole('button',{name:'Browse items',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByRole('button',{name:'Remove Food & drink filter'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Food & drink',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Browse packs',exact:true}).click()
  await page.reload()
  await expect(page.getByRole('button',{name:'Browse packs',exact:true})).toHaveAttribute('aria-pressed','true')
  for(const category of ['kind','type','tone','audio','strokes','status']){
    await page.getByRole('combobox',{name:'More pack categories'}).selectOption(category)
    await expect(page.getByRole('button',{name:/^Open pack /}).first()).toBeVisible()
  }
  await page.setViewportSize({width:1280,height:900})
  await page.getByRole('button',{name:'Topics',exact:true}).click()
  await page.screenshot({path:'/tmp/hanzi-dashboard-desktop.png',fullPage:false})
})

test('saved filter packs are searchable and can start directly with exactly their matching items',async({page})=>{
  await page.goto('/');await setFilters(page,{'Content':['Words'],'HSK':['HSK 1'],'Topic':['Food & drink'],'Audio':['Human audio']})
  await page.getByRole('button',{name:'Save selection',exact:true}).click()
  await page.getByRole('textbox',{name:'Name',exact:true}).fill('My food')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByRole('button',{name:'Browse packs',exact:true}).click()
  await expect(page.getByRole('region',{name:'Saved packs'}).getByRole('article',{name:'Pack My food'})).toBeVisible()
  await page.getByPlaceholder('Find a pack: food, HSK 1, numbers…').fill('My food')
  await page.getByRole('button',{name:'Practice pack My food',exact:true}).click()
  await expect(page.getByRole('combobox',{name:'Practice item'}).locator('option')).toHaveCount(4)
  await expect(page.getByRole('combobox',{name:'Practice item'})).toHaveValue('word:米饭')
  await page.getByRole('button',{name:'Back to filters'}).click()
  await expect(page.getByRole('heading',{name:'My food',exact:true}).first()).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button',{name:'Practice 4 matching items'})).toBeVisible()
})

test('direct pack play ignores stale review filters and dashboard review remains From memory',async({page})=>{
  test.setTimeout(60000)
  await page.goto('/review')
  await page.getByRole('button',{name:'Browse packs',exact:true}).click()
  await page.getByRole('button',{name:'Study sets',exact:true}).click()
  await page.getByRole('button',{name:'Practice pack Set 1 · Foundations',exact:true}).click()
  await expect(page.getByRole('combobox',{name:'Practice item'}).locator('option')).toHaveCount(40)
  await expect(page.getByRole('switch',{name:'From memory'})).toHaveAttribute('aria-checked','false')
  await page.getByRole('button',{name:'Autoplay',exact:true}).click()
  await page.getByRole('button',{name:'Hint',exact:true}).click()
  await draw(page,'一')
  await page.getByRole('button',{name:'Back to filters'}).click()
  await page.getByRole('button',{name:'Browse packs',exact:true}).click()
  // Guided completion is due in ten minutes; an unfinished hinted item is due immediately.
  await page.getByRole('button',{name:'Practice pack HSK 1',exact:true}).click()
  await page.getByRole('button',{name:'Hint',exact:true}).click()
  await page.getByRole('button',{name:'Back to filters'}).click()
  await page.getByRole('button',{name:'Browse packs',exact:true}).click()
  await page.getByRole('button',{name:/^Ready to review/}).click()
  await page.getByRole('button',{name:/^Practice \d+ matching items/}).click()
  await expect(page.getByRole('switch',{name:'From memory'})).toHaveAttribute('aria-checked','true')
})
