test('failed downloads retry; navigation cancels pending writers; storage failure keeps practice usable',async({page})=>{
  let fail=true
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('**/characters/*.json',route=>fail?route.abort():route.continue())
  await openItem(page)
  await expect(page.getByRole('status').filter({hasText:'Could not load this exercise'})).toBeVisible()
  fail=false;await page.getByRole('button',{name:'Retry loading'}).click()
  await page.evaluate(()=>{Storage.prototype.setItem=function(){throw new DOMException('Full','QuotaExceededError')}})
  await draw(page,'一')
  await expect(page.getByRole('alert').filter({hasText:'Device storage is unavailable'})).toBeVisible()
  await page.getByRole('button',{name:'Back to filters'}).click()
  expect(errors).toEqual([])
})
