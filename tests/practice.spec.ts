test('touch recall rejects a wrong stroke and saves hints in the same attempt',async({browser})=>{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  const page=await context.newPage();await openItem(page)
  await page.getByRole('switch',{name:'From memory'}).click()
  await expect(page.getByTestId('reference-character')).toHaveText('?')
  const tile=page.getByRole('img',{name:'Writing area 1 for hidden character'})
  await expect(tile).toHaveAttribute('aria-disabled','false')
  const box=(await tile.boundingBox())!
  await page.mouse.move(box.x+box.width-40,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+40,box.y+box.height/2,{steps:20});await page.mouse.up()
  await expect(page.getByRole('status').filter({hasText:'Try stroke 1 again'})).toBeVisible()
  await page.getByRole('button',{name:'Hint',exact:true}).click();await draw(page,'一',0,true)
  const attempt=await page.evaluate(()=>JSON.parse(localStorage.getItem('hanzi-practice:progress:v1')||'[]')[0])
  expect(attempt.mode).toBe('recall');expect(attempt.hints).toBe(1);expect(attempt.mistakes).toBeGreaterThan(0)
  await context.close()
})
