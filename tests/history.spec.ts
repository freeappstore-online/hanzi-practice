import {test,expect} from '@playwright/test'
import {draw,openLibrary} from './helpers'

const key='hanzi-practice:history:v1'
test('recent packs retain independent checkpoints, word outcomes, completion percentages and skipped items',async({page})=>{
  test.setTimeout(60000)
  await page.setViewportSize({width:320,height:800})
  await page.goto('/')
  await page.evaluate(()=>{
    localStorage.removeItem('hanzi-practice:history:v1')
    localStorage.setItem('hanzi-practice:preferences:v1',JSON.stringify({character:'一',autoplay:false}))
    localStorage.setItem('hanzi-practice:session:v1',JSON.stringify({ids:['char:一','char:二','char:三'],index:0,mode:'guided',completed:false}))
  })
  await page.reload()
  await page.getByRole('button',{name:'Resume Previous practice',exact:true}).click()
  await draw(page,'一')
  await expect(page.getByLabel('Completed',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Back to filters'}).click()
  const old=page.getByRole('article',{name:'Previous practice',exact:true})
  await expect(old.getByRole('progressbar')).toHaveAttribute('aria-valuenow','33')
  await expect(old.getByText('100% clean')).toBeVisible()
  await page.getByRole('button',{name:'Browse items',exact:true}).click()
  await page.getByPlaceholder('Search characters or words').fill('妈妈')
  await page.getByRole('button',{name:'Practice 1 matching items'}).click()
  await page.getByRole('button',{name:'Hint',exact:true}).click()
  await draw(page,'妈',0)
  expect(await page.evaluate(key=>Object.keys(JSON.parse(localStorage.getItem(key)!).runs.find((r:any)=>r.name==='妈妈').results).length,key)).toBe(0)
  await draw(page,'妈',1)
  await expect(page.getByText('Practice complete.',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Back to filters'}).click()
  const word=page.getByRole('article',{name:'妈妈',exact:true})
  await expect(word.getByRole('progressbar')).toHaveAttribute('aria-valuenow','100')
  await expect(word.getByText('0% clean')).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'All 2',exact:true}).click()
  await page.getByRole('button',{name:'Resume Previous practice',exact:true}).click()
  await expect(page.getByRole('combobox',{name:'Practice item'})).toHaveValue('char:二')
  await page.getByRole('button',{name:'Next item',exact:true}).click()
  await draw(page,'三')
  await expect(page.getByText('2/3 completed.',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Continue unfinished'}).click()
  await expect(page.getByRole('combobox',{name:'Practice item'})).toHaveValue('char:二')
  await page.getByRole('button',{name:'Autoplay',exact:true}).click()
  await draw(page,'二')
  await expect(page.getByText('Practice complete.',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Next item',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Back to filters'}).click()
  await expect(old.getByRole('progressbar')).toHaveAttribute('aria-valuenow','100')
  const before=await page.evaluate(()=>localStorage.getItem('hanzi-practice:progress:v1'))
  await page.getByRole('button',{name:'Open Previous practice',exact:true}).click()
  await expect(page.getByText('Practice complete.',{exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByText('Practice complete.',{exact:true})).toBeVisible()
  expect(await page.evaluate(()=>localStorage.getItem('hanzi-practice:progress:v1'))).toBe(before)
  await page.getByRole('button',{name:'Back to filters'}).click()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'/tmp/hanzi-history-mobile.png',fullPage:false})
})

test('new packs created in another tab remain available without changing the active queue',async({page,context})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Browse items',exact:true}).click()
  await page.getByPlaceholder('Search characters or words').fill('一')
  await page.getByRole('button',{name:/Practice \d+ matching items/}).click()
  const other=await context.newPage();await openLibrary(other)
  await other.getByPlaceholder('Search characters or words').fill('二')
  await other.getByRole('button',{name:/Practice \d+ matching items/}).click()
  await expect(page.getByRole('combobox',{name:'Practice item'})).toHaveValue('char:一')
  await page.getByRole('button',{name:'Back to filters'}).click()
  await page.getByRole('button',{name:'All 2',exact:true}).click()
  await expect(page.getByRole('region',{name:'Recent practice'}).getByRole('article')).toHaveCount(2)
  await page.reload()
  await page.getByRole('button',{name:'All 2',exact:true}).click()
  await expect(page.getByRole('region',{name:'Recent practice'}).getByRole('article')).toHaveCount(2)
})


test('browsing and reloading does not invent a practice run',async({page})=>{
  await page.goto('/')
  await page.reload()
  await expect(page.getByRole('region',{name:'Recent practice'})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Resume practice',exact:true})).toHaveCount(0)
})
